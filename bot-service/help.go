
package main

import "telegram-bot/session"

func helpText(state session.State) string {
    text := `📖 СПРАВКА ПО БОТУ

Доступные команды:

/start — регистрация и главное меню
/help — показать эту справку
/menu — вернуться в главное меню
/cancel — выйти из текущего режима
/anime <название> — найти аниме по названию

🔎 ПОИСК АНИМЕ

1. Нажмите «🔎 Поиск аниме».
2. Введите название, например: Наруто.
3. Бот отправит результаты поиска.
4. Можно сразу вводить следующее название.
5. Для выхода нажмите «❌ Выйти из режима».

📌 PINTEREST

Загрузка изображений по ссылке.
Сервис пока не подключён.

🎵 YOUTUBE

Загрузка аудио из видео по ссылке.
Сервис пока не подключён.
Используйте только контент, который разрешено скачивать.

⚙️ ОСОБЕННОСТИ

Каждый пользователь имеет собственный режим.
Режим сохраняется между сообщениями,
но сбрасывается при перезапуске бота.
`

    if state == session.AnimeSearch {
        text += "\n🟢 Сейчас активен поиск аниме."
    }

    return text
}
